// One-off generator: reads public/shared/unit-titles.js (client-side unit
// name data) and emits src/subject-units-data.ts, a plain TS data module
// mapping subject key -> { unitId: unitName }. Needed because the Worker
// (allowJs:false, src/**/*.ts only) can't import the public/ JS module
// directly for typecheck purposes, and duplicating 50+ subjects' unit
// names by hand would drift. Re-run this whenever unit-titles.js changes.
import * as titles from "../public/shared/unit-titles.js";

const SUBJECT_TO_EXPORT = {
  geometry: "geometryUnits", chemistry: "chemistryUnits", algebra1: "algebra1Units", algebra2: "algebra2Units",
  aplang: "aplangUnits", globalhistory: "globalHistoryUnits", apbiology: "apbiologyUnits", apush: "apushUnits",
  "us-history": "usHistoryUnits", physics: "physicsUnits", biology: "biologyUnits", precalc: "precalcUnits",
  "act-prep": "actPrepUnits", anatomy: "anatomyUnits", "ap-chemistry": "apChemistryUnits", "ap-csa": "apCsaUnits",
  "ap-euro": "apEuroUnits", "ap-macro": "apMacroUnits", "ap-micro": "apMicroUnits", "ap-physics": "apPhysicsUnits",
  "ap-psych": "apPsychUnits", "ap-stats": "apStatsUnits", "ap-usgov": "apUsgovUnits", "ap-world": "apWorldUnits",
  "ap-human-geography": "apHumanGeographyUnits", "art-history": "artHistoryUnits", astronomy: "astronomyUnits",
  "computer-science": "computerScienceUnits", "creative-writing": "creativeWritingUnits", "earth-science": "earthScienceUnits",
  economics: "economicsUnits", "english-10": "english10Units", "english-9": "english9Units",
  "environmental-science": "environmentalScienceUnits", "french-1": "french1Units", geography: "geographyUnits",
  "german-1": "german1Units", health: "healthUnits", journalism: "journalismUnits", "music-theory": "musicTheoryUnits",
  psychology: "psychologyUnits", "sat-math": "satMathUnits", "sat-reading": "satReadingUnits", sociology: "sociologyUnits",
  "spanish-1": "spanish1Units", "spanish-2": "spanish2Units", "spanish-3": "spanish3Units", "speech-debate": "speechDebateUnits",
  statistics: "statisticsUnits", "study-skills": "studySkillsUnits", "us-government": "usGovernmentUnits",
  "world-history": "worldHistoryUnits", calculus: "calculusUnits", "calc-ab": "calcAbUnits", "calc-bc": "calcBcUnits"
};

const data = {};
for (const [key, exportName] of Object.entries(SUBJECT_TO_EXPORT)) {
  const units = titles[exportName];
  if (!units) { console.error("Missing export:", exportName); process.exit(1); }
  const map = {};
  for (const u of units) map[u.id] = u.name;
  data[key] = map;
}

const out = `// GENERATED by scripts/gen-subject-units.mjs -- do not hand-edit.
// Mirrors public/shared/unit-titles.js so the Worker can look up unit
// display names server-side (e.g. for the study-group weak-spots aggregate)
// without importing client JS into the src/**/*.ts build.
export const SUBJECT_UNIT_NAMES: Record<string, Record<string, string>> = ${JSON.stringify(data, null, 2)};
`;

const fs = await import("node:fs");
fs.writeFileSync(new URL("../src/subject-units-data.ts", import.meta.url), out);
console.log("Wrote src/subject-units-data.ts");
